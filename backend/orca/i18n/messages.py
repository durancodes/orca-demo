def template_language(lang: str) -> str:
    return lang if lang in M else "en"


def t(key: str, lang: str, **kwargs) -> str:
    table = M.get(lang, M["en"])
    template = table.get(key) or M["en"].get(key, key)
    return template.format(**kwargs) if kwargs else template


def direction8(compass16: str) -> str:
    """Collapse a 16-point compass label to 8 points (NNE -> NE, ENE -> E, ...)."""
    mapping = {
        "N": "N", "NNE": "NE", "NE": "NE", "ENE": "E", "E": "E", "ESE": "SE", "SE": "SE", "SSE": "S",
        "S": "S", "SSW": "SW", "SW": "SW", "WSW": "W", "W": "W", "WNW": "NW", "NW": "NW", "NNW": "N",
    }
    return mapping.get(compass16, compass16)
